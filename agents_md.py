"""Plain-markdown AGENTS.md generator and validator.

Format contract (follows the Hermes context-files guidance):
- Line 1: a '# <title>' heading.
- '<!-- defuzz schema_version: 1 -->' marks the adopted-project contract.
- Four '## ' sections, in order: Purpose, Layout, Conventions & constraints, Build & test.
  Each has at least one non-empty line. Any normal markdown is allowed inside.
- Length is handled automatically, with no warnings, errors or questions. When the
  full guide would pass the line limit (default 40), the extra folder and convention
  bullets move to DETAILS_PATH and AGENTS.md links to it. Nothing is dropped.
- Model-supplied text (dir summaries, rule reasons, patterns) is sanitized to a single
  line with no shell syntax, backticks or URLs before it is rendered.
"""

from __future__ import annotations

import os
import re
import textwrap
from collections.abc import Collection
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Set, Tuple

from .catalog_list import escape_text
from .rules import _validate_safe_rel_prefix
from .safety import SafetyError, safe_write_text, verify_nofollow_within_root

DEFAULT_MAX_LINES = 40
MIN_ROOT_LINES = 11


def clamp_max_lines(max_lines: Any) -> int:
    """Return max_lines clamped to at least MIN_ROOT_LINES (11), or DEFAULT_MAX_LINES when unset."""
    if isinstance(max_lines, bool) or not isinstance(max_lines, int):
        return DEFAULT_MAX_LINES
    return max(MIN_ROOT_LINES, max_lines)
SCHEMA_VERSION = 1
SCHEMA_MARKER = f"<!-- defuzz schema_version: {SCHEMA_VERSION} -->"
DETAILS_PATH = ".adopt/AGENTS.details.md"
START_PROJECT_RULE = (
    "- To start a project: run `hermes defuzz list`, show the user the list, wait for "
    "their choice, then run `hermes defuzz new --template ID` or `--kit ID`. "
    "Never choose for the user. Never create a project inside this one."
)
GENERATED_NOTE = (
    "<!-- Generated by defuzz from .adopt/rules.json. Do not edit by hand: "
    "it is rewritten whenever the rules change. -->"
)

REQUIRED_SECTIONS: Tuple[str, ...] = (
    "Purpose",
    "Layout",
    "Conventions & constraints",
    "Build & test",
)

_FORBIDDEN_TOKENS_RE = re.compile(
    r"(?:https?://|ftp://|\$\b|\$\{|\$\(|;|&&|\|\||[|<>`])"
)
_CONTROL_CHARS_RE = re.compile(r"[\x00-\x08\x0b-\x0c\x0e-\x1f\x7f]")
_LAYOUT_DIR_RE = re.compile(r"^- `(?P<dir>[^`]+?)/`")
_KIT_END_RE = re.compile(r"^<!-- kit:(?P<id>[^\s>]+)\s+end\s*-->\s*$")
_FENCE_OPEN_RE = re.compile(r"^(?P<fence>`{3,}|~{3,})")
_KIT_LAYOUT_BULLET_RE = re.compile(r"^\s*-\s+`(?P<dir>[^`\r\n]+?)/`\s*:")


def _update_fence_state(stripped: str, active_fence: Optional[str]) -> Tuple[Optional[str], bool]:
    """Update CommonMark-style fenced code block state for a line starting at column 0.

    Returns (new_active_fence, is_fence_or_fenced_line).
    """
    m = _FENCE_OPEN_RE.match(stripped)
    if active_fence is None:
        if m is not None:
            fence = m.group("fence")
            rest = stripped[len(fence) :]
            if fence[0] != "`" or "`" not in rest:
                return fence, True
        return None, False
    if (
        m is not None
        and m.group("fence")[0] == active_fence[0]
        and len(m.group("fence")) >= len(active_fence)
        and stripped[len(m.group("fence")) :].strip() == ""
    ):
        return None, True
    return active_fence, True


def _kit_begin_id(line: str) -> Tuple[str, bool]:
    """Parse a column-0 kit begin marker line; return (kit_id, is_well_formed_begin)."""
    if not line.startswith("<!-- kit:") or " begin" not in line:
        return "", False
    rest = line[len("<!-- kit:") :]
    parts = rest.split(None, 1)
    kit_id = parts[0] if (parts and not rest[0].isspace() and parts[0] != "begin") else ""
    if not kit_id:
        return "", False
    is_valid = (" begin" in rest[len(kit_id) :]) and line.rstrip().endswith("-->")
    return kit_id, is_valid


def _extract_kit_blocks(raw_text: str) -> Tuple[List[Tuple[str, str]], List[str]]:
    """Extract well-formed kit blocks and dropped/malformed kit IDs from existing AGENTS.md text."""
    entries: List[Tuple[str, bool, str]] = []
    open_id: Optional[str] = None
    open_start: int = 0
    offset = 0
    active_fence: Optional[str] = None

    for line in raw_text.splitlines(keepends=True):
        line_len = len(line)
        stripped = line.rstrip("\r\n")
        active_fence, in_fence = _update_fence_state(stripped, active_fence)
        if in_fence:
            offset += line_len
            continue

        end_match = _KIT_END_RE.match(stripped)
        if end_match is not None:
            end_id = end_match.group("id")
            if open_id == end_id:
                block_slice = raw_text[open_start : offset + line_len]
                entries.append((end_id, True, block_slice))
                open_id = None
            elif open_id is None:
                entries.append((end_id, False, ""))
            offset += line_len
            continue

        if stripped.startswith("<!-- kit:") and " begin" in stripped:
            if open_id is not None:
                entries.append((open_id, False, ""))
                open_id = None
            kit_id, is_valid_begin = _kit_begin_id(stripped)
            if is_valid_begin:
                open_id = kit_id
                open_start = offset
            elif kit_id:
                entries.append((kit_id, False, ""))
        offset += line_len

    if open_id is not None:
        entries.append((open_id, False, ""))

    id_counts: Dict[str, int] = {}
    for kit_id, _, _ in entries:
        id_counts[kit_id] = id_counts.get(kit_id, 0) + 1

    preserved: List[Tuple[str, str]] = []
    dropped: List[str] = []
    for kit_id, is_valid, block_slice in entries:
        if not is_valid or id_counts.get(kit_id, 0) > 1:
            if kit_id and kit_id not in dropped:
                dropped.append(kit_id)
        else:
            preserved.append((kit_id, block_slice))
    return preserved, dropped


def _dirs_listed_in_kit_blocks(blocks: Sequence[str]) -> Set[str]:
    """Return normalized relative directory paths listed as `- `<dir>/`: ...` in preserved kit blocks."""
    listed: Set[str] = set()
    for block in blocks:
        for line in block.splitlines():
            m = _KIT_LAYOUT_BULLET_RE.match(line)
            if m is not None:
                raw_dir = m.group("dir")
                try:
                    listed.add(_validate_safe_rel_prefix(raw_dir, "kit_block.dir", allow_dot=False))
                except SafetyError:
                    listed.add(raw_dir.strip("/"))
    return listed


def _sanitize_token(text: Any, max_len: Optional[int] = None) -> str:
    # Rules-derived text: control, bidi and format characters become visible escapes.
    # The escapes are plain characters, so text placer already escaped comes out unchanged.
    cleaned = escape_text(" ".join(str(text).split()))
    while True:
        sanitized = _FORBIDDEN_TOKENS_RE.sub("", cleaned).strip()
        if sanitized == cleaned:
            break
        cleaned = sanitized
    if max_len is not None and len(cleaned) > max_len:
        cleaned = re.sub(r"[\W_]+$", "", cleaned[:max_len])
    return cleaned or "n/a"


def validate_agents_md(
    content: str,
    *,
    allowed_dirs: Optional[Set[str]] = None,
) -> List[Dict[str, Any]]:
    """Validate a plain-markdown AGENTS.md.

    Returns the sections in order as [{"heading": str, "lines": [str, ...]}, ...].
    """
    raw_lines = content.splitlines()
    if _CONTROL_CHARS_RE.search(content):
        raise SafetyError("AGENTS.md contains control characters")
    non_empty = [ln for ln in raw_lines if ln.strip()]
    if not non_empty or not non_empty[0].startswith("# ") or not non_empty[0][2:].strip():
        raise SafetyError("AGENTS.md must start with a '# <title>' heading")
    if SCHEMA_MARKER not in (ln.strip() for ln in non_empty[1:2]):
        raise SafetyError(f"AGENTS.md must have {SCHEMA_MARKER} right after the title")

    sections: List[Dict[str, Any]] = []
    in_kit_id: Optional[str] = None
    active_fence: Optional[str] = None
    for ln in non_empty[1:]:
        active_fence, in_fence = _update_fence_state(ln, active_fence)
        if in_kit_id is not None:
            if not in_fence:
                end_m = _KIT_END_RE.match(ln)
                if end_m is not None and end_m.group("id") == in_kit_id:
                    in_kit_id = None
            continue
        if not in_fence:
            kid, is_valid_begin = _kit_begin_id(ln)
            if is_valid_begin:
                in_kit_id = kid
                continue
        if not in_fence and ln.startswith("## "):
            sections.append({"heading": ln[3:].strip(), "lines": []})
        elif sections:
            sections[-1]["lines"].append(ln)

    headings = [s["heading"] for s in sections]
    missing = [h for h in REQUIRED_SECTIONS if h not in headings]
    if missing:
        raise SafetyError(f"AGENTS.md is missing section(s): {', '.join(missing)}")
    order = [headings.index(h) for h in REQUIRED_SECTIONS]
    if order != sorted(order):
        raise SafetyError(f"AGENTS.md sections must appear in order: {', '.join(REQUIRED_SECTIONS)}")
    for s in sections:
        if s["heading"] in REQUIRED_SECTIONS and not s["lines"]:
            raise SafetyError(f"AGENTS.md section '{s['heading']}' is empty")

    if allowed_dirs is not None:
        for ln in sections[headings.index("Layout")]["lines"]:
            m = _LAYOUT_DIR_RE.match(ln)
            if m and m.group("dir").strip("/") not in allowed_dirs:
                raise SafetyError(f"AGENTS.md Layout references undeclared directory {m.group('dir')!r}")
    return sections


def render_agents_md(**kwargs: Any) -> str:
    """Render everything as one self-contained AGENTS.md (no length target, no details file).

    Use render_agents_md_files() to get a root guide within a line target plus
    the linked details file.
    """
    kwargs.pop("max_lines", None)
    files = render_agents_md_files(max_lines=10**9, **kwargs)
    assert list(files) == ["AGENTS.md"]
    return files["AGENTS.md"]


def _layout_bullets_and_allowed_dirs(
    declared_dirs: Dict[str, Tuple[str, str]], omit_layout_dirs: Collection[str]
) -> Tuple[List[str], Set[str]]:
    """Build optional layout bullets and all directories allowed by the validator."""
    omitted_layout = set(omit_layout_dirs)
    allowed_dir_set: Set[str] = {"_inbox", "_archive"}
    layout_optional: List[str] = []
    for dname in sorted(declared_dirs.keys()):
        try:
            clean_d = _validate_safe_rel_prefix(dname, "declared_dirs.dir", allow_dot=False)
        except SafetyError:
            continue
        if clean_d in {"_inbox", "_archive"}:
            continue
        allowed_dir_set.add(clean_d)
        if clean_d in omitted_layout:
            continue
        summary, why = declared_dirs[dname]
        layout_optional.append(
            f"- `{clean_d}/` — {_sanitize_token(summary)} ({_sanitize_token(why)})"
        )
    return layout_optional, allowed_dir_set


def _placement_bullets(placement_rules: Sequence[Dict[str, Any]]) -> List[str]:
    """Render the first placement rule for each sanitized kind, in input order."""
    bullets: List[str] = []
    seen_kinds: Set[str] = set()
    for idx, rule in enumerate(placement_rules):
        kind = re.sub(r"[^a-z0-9_-]", "", str(rule.get("kind") or f"r{idx}").lower())[:24]
        if not kind or kind in seen_kinds:
            continue
        seen_kinds.add(kind)
        exts = ", ".join(f"`{_sanitize_token(e)}`" for e in sorted(rule.get("match_ext") or [])) or "any"
        dest = _sanitize_token(str(rule.get("dest_dir") or "_inbox").strip("/"))
        reason = _sanitize_token(rule.get("reason") or "placement rule")
        bullets.append(f"- {exts} files go in `{dest}/` ({reason}).")
    return bullets


def _assemble_guide_sections(
    *, slug: str, max_lines: int, clean_kit_ids: Sequence[str],
    purpose: List[str], layout: List[str], conv: List[str], build: List[str],
    blank_before_headings: bool,
) -> List[str]:
    """Assemble guide sections, wrapping readable guides without splitting kit purpose text."""
    out = [f"# {slug}", SCHEMA_MARKER, GENERATED_NOTE]
    readable = max_lines >= DEFAULT_MAX_LINES
    if readable:
        out.insert(1, "")
    for heading, body in (
        ("Purpose", purpose),
        ("Layout", layout),
        ("Conventions & constraints", conv),
        ("Build & test", build),
    ):
        if blank_before_headings:
            out.append("")
        out.append(f"## {heading}")
        if readable:
            out.append("")
            if heading == "Purpose" and clean_kit_ids:
                out.extend(body)
            else:
                for line in body:
                    out.extend(textwrap.wrap(
                        line, width=80,
                        subsequent_indent="  " if line.startswith("- ") else "",
                        break_long_words=False, break_on_hyphens=False,
                    ))
        else:
            out.extend(body)
    return out


def render_agents_md_files(
    *,
    project_slug: str,
    declared_dirs: Dict[str, Tuple[str, str]],
    placement_rules: Sequence[Dict[str, Any]],
    lfs_patterns: Sequence[str] = (),
    ignore_patterns: Sequence[str] = (),
    local_only_branches: Sequence[str] = (),
    max_lines: int = DEFAULT_MAX_LINES,
    reserve_lines: int = 0,
    omit_layout_dirs: Collection[str] = (),
    kit_ids: Sequence[str] = (),
) -> Dict[str, str]:
    """Render AGENTS.md, plus DETAILS_PATH when the content needs more room.

    Returns {"AGENTS.md": text} or {"AGENTS.md": text, DETAILS_PATH: text}.
    declared_dirs maps folder_name -> (summary, why). Never raises over length:
    configured values below MIN_ROOT_LINES (11) are clamped to MIN_ROOT_LINES,
    then reserve_lines is subtracted from that total budget. Reservations must
    leave at least 10 lines for the required guide structure. Bullets that do not
    fit move to the details file in full.
    """
    max_lines = clamp_max_lines(max_lines)
    if isinstance(reserve_lines, bool) or not isinstance(reserve_lines, int) or reserve_lines < 0:
        raise ValueError("reserve_lines must be a non-negative integer")
    max_lines -= reserve_lines
    if max_lines < 10:
        raise ValueError("reserve_lines leaves fewer than 10 required guide lines")

    slug = _sanitize_token(project_slug, 64)

    clean_kit_ids = [_sanitize_token(kid, 64) for kid in kit_ids if str(kid).strip()]
    if clean_kit_ids:
        noun = "kit" if len(clean_kit_ids) == 1 else "kits"
        purpose = [
            f"`{slug}` was set up by defuzz from the {', '.join(clean_kit_ids)} {noun}. "
            "Its folders and rules are in the kit section below."
        ]
    else:
        purpose = [
            f"`{slug}` is a workspace adopted by defuzz. "
            "It is a copy, and the original folder was never modified."
        ]

    layout_optional, allowed_dir_set = _layout_bullets_and_allowed_dirs(declared_dirs, omit_layout_dirs)
    if clean_kit_ids:
        layout_fixed = [
            "- `_inbox/` — files with no placement rule are moved here; ask where they belong, then move them",
        ]
        conv_fixed = [
            "- Never delete files without approval.",
            "- New files are placed by the rules in `.adopt/rules.json`.",
            START_PROJECT_RULE,
        ]
    else:
        layout_fixed = [
            "- `_inbox/` — new files of an unknown kind land here",
            "- `_archive/` — retired clutter, preserved byte-for-byte",
        ]
        conv_fixed = [
            "- Never delete files. Move retired ones to `_archive/`.",
            "- New files are placed by the rules in `.adopt/rules.json`.",
            START_PROJECT_RULE,
        ]
    conv_optional = _placement_bullets(placement_rules)
    if lfs_patterns:
        pats = ", ".join(f"`{_sanitize_token(p)}`" for p in sorted(set(lfs_patterns)))
        conv_optional.append(f"- Git LFS tracks {pats}.")
    if ignore_patterns:
        pats = ", ".join(f"`{_sanitize_token(p)}`" for p in sorted(set(ignore_patterns)))
        conv_optional.append(f"- Git ignores {pats}.")
    if local_only_branches:
        names = ", ".join(f"`{_sanitize_token(b)}`" for b in sorted(set(local_only_branches)))
        conv_optional.append(f"- Local-only branches kept in the copy: {names}.")

    build = ["- Not detected yet."]

    pointer = f"- More in `{DETAILS_PATH}`."

    def assemble(
        n_layout: int,
        n_conv: int,
        *,
        include_fixed_layout: bool = True,
        include_fixed_conv: bool = True,
        blank_before_headings: bool = True,
    ) -> List[str]:
        layout = layout_optional[:n_layout] + (layout_fixed if include_fixed_layout else [])
        conv = (conv_fixed if include_fixed_conv else []) + conv_optional[:n_conv]
        if n_layout < len(layout_optional) or not include_fixed_layout:
            layout.append(pointer)
        if n_conv < len(conv_optional) or not include_fixed_conv:
            conv.append(pointer)
        return _assemble_guide_sections(
            slug=slug, max_lines=max_lines, clean_kit_ids=clean_kit_ids,
            purpose=purpose, layout=layout, conv=conv, build=build,
            blank_before_headings=blank_before_headings,
        )

    n_layout, n_conv = len(layout_optional), len(conv_optional)
    inc_fixed_layout = True
    inc_fixed_conv = True
    blank_headings = True
    lines = assemble(n_layout, n_conv)
    # Shrink conventions first, then layout, then fixed bullets, then blank lines until it fits.
    while len(lines) > max_lines and (n_conv or n_layout):
        if n_conv:
            n_conv -= 1
        else:
            n_layout -= 1
        lines = assemble(n_layout, n_conv)
    if len(lines) > max_lines:
        inc_fixed_conv = False
        lines = assemble(
            n_layout,
            n_conv,
            include_fixed_layout=inc_fixed_layout,
            include_fixed_conv=inc_fixed_conv,
            blank_before_headings=blank_headings,
        )
    if len(lines) > max_lines:
        inc_fixed_layout = False
        lines = assemble(
            n_layout,
            n_conv,
            include_fixed_layout=inc_fixed_layout,
            include_fixed_conv=inc_fixed_conv,
            blank_before_headings=blank_headings,
        )
    if len(lines) > max_lines:
        blank_headings = False
        lines = assemble(
            n_layout,
            n_conv,
            include_fixed_layout=inc_fixed_layout,
            include_fixed_conv=inc_fixed_conv,
            blank_before_headings=blank_headings,
        )
    if len(lines) > max_lines:
        # Keep all four required sections and their bodies. The generated notice
        # is metadata, so it can share the Purpose body at the minimum budget.
        lines.remove(GENERATED_NOTE)
        purpose_index = lines.index("## Purpose") + 1
        lines[purpose_index] += " " + GENERATED_NOTE
    assert len(lines) <= max_lines

    content = "\n".join(lines) + "\n"
    validate_agents_md(content, allowed_dirs=allowed_dir_set)
    files = {"AGENTS.md": content}

    overflowed = (
        n_layout < len(layout_optional)
        or n_conv < len(conv_optional)
        or not inc_fixed_layout
        or not inc_fixed_conv
    )
    if overflowed:
        details = [f"# {slug}: AGENTS.md details", GENERATED_NOTE, "",
                   "Full lists linked from the root `AGENTS.md`."]
        details_layout = layout_optional + (layout_fixed if not inc_fixed_layout else [])
        details_conv = (conv_fixed if not inc_fixed_conv else []) + conv_optional
        if details_layout:
            details += ["", "## Layout", *details_layout]
        if details_conv:
            details += ["", "## Conventions & constraints", *details_conv]
        files[DETAILS_PATH] = "\n".join(details) + "\n"
    return files


def render_from_rules(
    rules_data: Dict[str, Any],
    *,
    reserve_lines: int = 0,
    omit_layout_dirs: Collection[str] = (),
    kit_ids: Sequence[str] = (),
) -> Dict[str, str]:
    """Render the guide files from a .adopt/rules.json payload (same rules -> same files)."""
    declared = {
        str(d["dir"]): (str(d.get("summary") or ""), str(d.get("why") or ""))
        for d in (rules_data.get("declared_dirs") or [])
        if isinstance(d, dict) and d.get("dir")
    }
    max_lines = clamp_max_lines(rules_data.get("agents_md_max_lines"))
    return render_agents_md_files(
        project_slug=str(rules_data.get("project_slug") or "project"),
        declared_dirs=declared,
        placement_rules=list(rules_data.get("placement_rules") or []),
        lfs_patterns=list(rules_data.get("lfs_patterns") or []),
        ignore_patterns=list(rules_data.get("ignore_patterns") or []),
        local_only_branches=list(rules_data.get("local_only_branches") or []),
        max_lines=max_lines,
        reserve_lines=reserve_lines,
        omit_layout_dirs=omit_layout_dirs,
        kit_ids=kit_ids,
    )


def write_agents_md(
    root: "os.PathLike[str] | str",
    rules_data: Dict[str, Any],
    *,
    reserve_lines: int = 0,
    preserve_kit_blocks: bool = False,
    kit_ids: Optional[Collection[str]] = None,
) -> Dict[str, Any]:
    """Regenerate AGENTS.md (and the details file) in root from rules_data.

    reserve_lines leaves space within the effective total cap for caller-added
    lines (such as the componentize pointer), without changing persisted rules.
    A details file left from an earlier run is rewritten to a short stub rather
    than deleted, so it never goes stale. When preserve_kit_blocks is True,
    preserves well-formed kit blocks (filtered by kit_ids when provided) from
    an existing AGENTS.md in root.
    """
    existing_agents = verify_nofollow_within_root(Path(root), "AGENTS.md")
    preserved_blocks: List[Tuple[str, str]] = []
    dropped_ids: List[str] = []
    if (
        preserve_kit_blocks
        and existing_agents.exists()
        and existing_agents.is_file()
        and not os.path.islink(existing_agents)
    ):
        raw_existing = existing_agents.read_bytes().decode("utf-8", errors="replace")
        preserved_blocks, dropped_ids = _extract_kit_blocks(raw_existing)
        if kit_ids is not None:
            allowed_kit_ids = set(kit_ids)
            preserved_blocks = [
                (kid, blk) for kid, blk in preserved_blocks if kid in allowed_kit_ids
            ]
            dropped_ids = [kid for kid in dropped_ids if kid in allowed_kit_ids]

    preserved_ids = [kit_id for kit_id, _ in preserved_blocks]
    omit_dirs = _dirs_listed_in_kit_blocks([block for _, block in preserved_blocks])
    files = render_from_rules(
        rules_data,
        reserve_lines=reserve_lines,
        omit_layout_dirs=omit_dirs,
        kit_ids=preserved_ids,
    )
    if preserved_blocks:
        parts = [files["AGENTS.md"].rstrip("\n")]
        for _, block in preserved_blocks:
            if parts[-1].endswith(("\n", "\r")):
                parts.append("\n" + block)
            else:
                parts.append("\n\n" + block)
        combined = "".join(parts)
        if not combined.endswith(("\n", "\r")):
            combined += "\n"
        files["AGENTS.md"] = combined

    overflow = DETAILS_PATH in files
    if not overflow and os.path.lexists(os.path.join(os.fspath(root), DETAILS_PATH)):
        slug = _sanitize_token(rules_data.get("project_slug") or "project", 64)
        files[DETAILS_PATH] = (
            f"# {slug}: AGENTS.md details\n{GENERATED_NOTE}\n\n"
            "Everything currently fits in the root `AGENTS.md`.\n"
        )
    for rel, text in files.items():
        safe_write_text(root, rel, text, overwrite=True)
    return {
        "paths": sorted(files),
        "overflow": overflow,
        "kit_blocks_preserved": preserved_ids,
        "kit_blocks_dropped": dropped_ids,
    }
