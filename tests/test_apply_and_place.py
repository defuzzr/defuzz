    def test_apply_writes_ignore_and_lfs_before_baseline_commit_and_rewrites_links(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            src = base / "source_proj"
            copy_dir = base / "copy_proj"
            staging = base / "staging"
            src.mkdir()
            staging.mkdir()

            # Create messy no-git folder with loose .md files, secret .env, and an internal-absolute symlink
            for i in range(6):
                (src / f"doc_{i}.md").write_text(f"# Doc {i}\n", encoding="utf-8")
            fake_secret = "ghp_" + ("9aBcDeFgHiJkLmNoPqRsTuVwXyZ0123456789"[:36])
            (src / ".env").write_text(f"GITHUB_TOKEN={fake_secret}\n", encoding="utf-8")
            (src / "src").mkdir()
            (src / "src" / "main.py").write_text("print('ok')\n", encoding="utf-8")
            os.symlink(str(src / "doc_0.md"), str(src / "latest_doc.md"))

            copy_tree_nofollow(src, copy_dir, staging_root=staging)
            inv = scan_folder(copy_dir, source_root=src, out_path=staging / "inventory.json")
            rules_spec = build_deterministic_fallback_rules(inv)

            report = apply_rules_to_copy(
                copy_dir,
                inv,
                rules_spec,
                source_root=src,
                staging_root=staging,
                report_out_path=staging / "report.json",
                agents_md_max_lines=20,
            )

            # Tight limit: overflow goes to the details file, no error
            self.assertTrue(report["agents_md_overflow"])
            self.assertEqual(report["agents_md_files"], [".adopt/AGENTS.details.md", "AGENTS.md"])
            self.assertLessEqual(len((copy_dir / "AGENTS.md").read_text().splitlines()), 20)
            self.assertIn("## Layout", (copy_dir / ".adopt" / "AGENTS.details.md").read_text())

            self.assertTrue(report["baseline_commit_sha"])
            self.assertEqual(report["counts"]["moved"], 6)
            self.assertEqual(report["counts"]["secrets_locked_to_ignore"], 1)

            # Verify .env is left behind in src (not in copy_dir), ignored in .gitignore, and NOT tracked in git
            self.assertFalse((copy_dir / ".env").exists())
            self.assertTrue((src / ".env").is_file())
            self.assertIn(".env", (copy_dir / ".gitignore").read_text(encoding="utf-8").splitlines())
            tracked_proc = run_git_hardened(copy_dir, ["ls-files"])
            tracked_list = tracked_proc.stdout.decode("utf-8").splitlines()
            self.assertNotIn(".env", tracked_list)
            self.assertIn("docs/doc_0.md", tracked_list)
            self.assertIn("AGENTS.md", tracked_list)
            self.assertIn("TOOLS.lock", tracked_list)
            self.assertTrue((copy_dir / "TOOLS.lock").is_file())
            adopted_tree = (
                run_git_hardened(copy_dir, ["ls-tree", "-r", "--name-only", report["adopted_commit_sha"]])
                .stdout.decode("utf-8")
                .splitlines()
            )
            self.assertIn("TOOLS.lock", adopted_tree)
            self.assertIn(".adopt/AGENTS.details.md", tracked_list)
            for rel in ("AGENTS.md", ".adopt/AGENTS.details.md"):
                self.assertIn("Generated by defuzz", (copy_dir / rel).read_text())

            # Changing the rules regenerates the guide, overwriting hand edits
            (copy_dir / ".adopt" / "AGENTS.details.md").write_text("hand edit\n")
            add_placement_rule(copy_dir, ".blend", "assets/3d", kind="blend")
            guide = (copy_dir / "AGENTS.md").read_text() + (copy_dir / ".adopt" / "AGENTS.details.md").read_text()
            self.assertIn("`assets/3d/`", guide)
            self.assertNotIn("hand edit", guide)

            # Verify internal-absolute symlink was rewritten to relative target pointing at docs/doc_0.md
            self.assertEqual(os.readlink(str(copy_dir / "latest_doc.md")), "docs/doc_0.md")

            # Verify source folder is 100% untouched
            self.assertFalse((src / ".git").exists())
            self.assertTrue((src / "doc_0.md").is_file())
            self.assertFalse((src / "docs").exists())

    def test_add_placement_rule_stages_rules_and_first_overflow_details_file(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            src = base / "source_proj"
            copy_dir = base / "copy_proj"
            staging = base / "staging"
            src.mkdir()
            staging.mkdir()
            (src / "README.md").write_text("# Demo\n", encoding="utf-8")
            (src / "src").mkdir()
            (src / "src" / "main.py").write_text("print(1)\n", encoding="utf-8")

            copy_tree_nofollow(src, copy_dir, staging_root=staging)
            inv = scan_folder(copy_dir, source_root=src, out_path=staging / "inventory.json")
            rules_spec = build_deterministic_fallback_rules(inv)

            # Set a max_lines where initial apply fits in AGENTS.md without overflow,
            # then adding rules triggers the first overflow into .adopt/AGENTS.details.md.
            report = apply_rules_to_copy(
                copy_dir,
                inv,
                rules_spec,
                source_root=src,
                staging_root=staging,
                agents_md_max_lines=40,
            )
            self.assertFalse(report["agents_md_overflow"])
            self.assertFalse((copy_dir / ".adopt" / "AGENTS.details.md").exists())
            initial_lines = report["agents_md_lines"]
            rules_file = copy_dir / ".adopt" / "rules.json"
            rules_json = json.loads(rules_file.read_text(encoding="utf-8"))
            rules_json["agents_md_max_lines"] = initial_lines
            rules_file.write_text(json.dumps(rules_json, indent=2) + "\n", encoding="utf-8")
            trust_project(copy_dir)

            # Adding one rule now pushes AGENTS.md over initial_lines and triggers the first overflow
            add_placement_rule(copy_dir, ".xyz", "assets/xyz", kind="xyz")

            self.assertTrue((copy_dir / ".adopt" / "AGENTS.details.md").is_file())
            tracked = run_git_hardened(copy_dir, ["ls-files"]).stdout.decode("utf-8").splitlines()
            self.assertIn(".adopt/rules.json", tracked)
            self.assertIn("AGENTS.md", tracked)
            self.assertIn(".adopt/AGENTS.details.md", tracked)

            # Working tree changes to rules and generated docs should be staged in index (no unstaged diff)
            unstaged = run_git_hardened(
                copy_dir,
                ["diff", "--name-only", "--", ".adopt/rules.json", "AGENTS.md", ".adopt/AGENTS.details.md"],
            ).stdout.decode("utf-8").splitlines()
            self.assertEqual(unstaged, [])
            staged = run_git_hardened(
                copy_dir,
                ["diff", "--cached", "--name-only"],
            ).stdout.decode("utf-8").splitlines()
            self.assertIn(".adopt/rules.json", staged)
            self.assertIn("AGENTS.md", staged)
            self.assertIn(".adopt/AGENTS.details.md", staged)

            # If max_lines later increases so overflow is no longer needed, the stub details file is also staged
            rules_json = json.loads(rules_file.read_text(encoding="utf-8"))
            rules_json["agents_md_max_lines"] = 100
            rules_file.write_text(json.dumps(rules_json, indent=2) + "\n", encoding="utf-8")
            trust_project(copy_dir)
            add_placement_rule(copy_dir, ".abc", "assets/abc", kind="abc")
            self.assertIn(
                "Everything currently fits",
                (copy_dir / ".adopt" / "AGENTS.details.md").read_text(encoding="utf-8"),
            )
            unstaged_after = run_git_hardened(
                copy_dir,
                ["diff", "--name-only", "--", ".adopt/rules.json", "AGENTS.md", ".adopt/AGENTS.details.md"],
            ).stdout.decode("utf-8").splitlines()
            self.assertEqual(unstaged_after, [])

    def test_pre_tool_call_placement_and_exclusions_and_undo(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            proj = Path(tmp) / "adopted_proj"
            (proj / ".adopt").mkdir(parents=True)
            (proj / "src").mkdir()
            (proj / "docs").mkdir()
            (proj / "_inbox").mkdir()
            (proj / "existing.md").write_text("existing\n", encoding="utf-8")
            (proj / ".adopt" / "rules.json").write_text(
                json.dumps({
                    "schema": 1,
                    "project_slug": "adopted_proj",
                    "declared_dirs": [{"dir": "docs", "summary": "docs", "why": "docs"}],
                    "placement_rules": [
                        {"kind": "docs", "match_ext": [".md"], "dest_dir": "docs", "lfs": False, "reason": "docs"}
                    ],
                }),
                encoding="utf-8",
            )
            trust_project(proj)

            # 1. Existing file edit -> never relocated
            res_existing = on_pre_tool_call(
                tool_name="write_file",
                args={"path": str(proj / "existing.md"), "content": "updated"},
                tool_call_id="tc1",
            )
            self.assertIsNone(res_existing)

            # 2. Root AGENTS.md / README.md / dotfile / src/ file -> never relocated
            for exempt_rel in ("AGENTS.md", "README.md", ".eslintrc.json", "src/new_module.py", "docs/already_in_docs.md"):
                res_ex = on_pre_tool_call(
                    tool_name="write_file",
                    args={"path": str(proj / exempt_rel), "content": "x"},
                )
                self.assertIsNone(res_ex, f"Expected None for exempt path {exempt_rel}")

            # 3. New loose .md file at root -> routed to docs/
            res_md = on_pre_tool_call(
                tool_name="write_file",
                args={"path": str(proj / "design_note.md"), "content": "# Note"},
                tool_call_id="tc_md",
            )
            self.assertIsNotNone(res_md)
            assert res_md is not None
            self.assertEqual(res_md["action"], "modify")
            self.assertEqual(res_md["args"]["path"], str(proj / "docs" / "design_note.md"))

            # Simulate write_file completion and transform_tool_result note
            (proj / "docs" / "design_note.md").write_text("# Note\n", encoding="utf-8")
            transformed = on_transform_tool_result(
                tool_name="write_file",
                args=res_md["args"],
                result=json.dumps({"verified": True, "resolved_path": res_md["args"]["path"]}),
                tool_call_id="tc_md",
            )
            self.assertIsNotNone(transformed)
            assert transformed is not None
            parsed_res = json.loads(transformed)
            self.assertEqual(parsed_res["placed_by_adopt"]["to"], "docs/design_note.md")
            log = json.loads((proj / ".adopt" / "place-log.json").read_text(encoding="utf-8"))
            self.assertEqual([e["placed_rel"] for e in log], ["docs/design_note.md"])

            # 3b. Subfolders are kept; a failed write is never logged
            res_sub = on_pre_tool_call(
                tool_name="write_file",
                args={"path": str(proj / "notes" / "2026" / "plan.md"), "content": "x"},
                tool_call_id="tc_sub",
            )
            assert res_sub is not None
            self.assertEqual(res_sub["args"]["path"], str(proj / "docs" / "notes" / "2026" / "plan.md"))
            self.assertIsNone(on_transform_tool_result(
                tool_name="write_file",
                args=res_sub["args"],
                result=json.dumps({"error": "disk full"}),
                tool_call_id="tc_sub",
            ))
            log = json.loads((proj / ".adopt" / "place-log.json").read_text(encoding="utf-8"))
            self.assertEqual(len(log), 1)

            # 4. Unknown file extension -> routed to _inbox/
            res_unk = on_pre_tool_call(
                tool_name="write_file",
                args={"path": str(proj / "mystery.customext"), "content": "data"},
                tool_call_id="tc_unk",
            )
            self.assertIsNotNone(res_unk)
            assert res_unk is not None
            self.assertEqual(res_unk["args"]["path"], str(proj / "_inbox" / "mystery.customext"))
            (proj / "_inbox" / "mystery.customext").write_text("data", encoding="utf-8")

            # 5. Add rule for .customext -> sweep _inbox/ moves mystery.customext to custom_dir/
            add_placement_rule(proj, ".customext", "custom_dir", kind="custom")
            swept = sweep_inbox(proj)
            self.assertEqual(len(swept), 1)
            self.assertTrue((proj / "custom_dir" / "mystery.customext").is_file())

            # 6. Undo restores mystery.customext back to _inbox/
            undone = undo_placements(proj, count=1)
            self.assertEqual(len(undone), 1)
            self.assertTrue((proj / "_inbox" / "mystery.customext").is_file())

    def test_provenance_and_rules_hash_enforced_outside_project_folder(self) -> None:
        import io
        from contextlib import redirect_stdout
        from hermes_plugins.defuzz.safety import SafetyError
        from hermes_plugins.defuzz.state_store import get_project, is_registered, record_project, state_db_path

        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            src = base / "src_proj"
            copy_dir = base / "copy_proj"
            forged_dir = base / "forged_proj"
            legacy_dir = base / "legacy_proj"
            staging = base / "staging"
            for d in (src, forged_dir, legacy_dir, staging):
                d.mkdir()
            (src / "README.md").write_text("# Reg\n", encoding="utf-8")
            (src / "src").mkdir()
            (src / "src" / "app.py").write_text("x = 1\n", encoding="utf-8")

            # 1. Forged minimal valid .adopt/rules.json => hook is a no-op (even before state.db exists)
            default_db = state_db_path()
            self.assertFalse(default_db.exists())
            (forged_dir / ".adopt").mkdir()
            (forged_dir / ".adopt" / "rules.json").write_text(
                json.dumps({
                    "schema": 1,
                    "schema_version": 1,
                    "project_slug": "forged_proj",
                    "declared_dirs": [{"dir": "docs", "summary": "docs", "why": "docs"}],
                    "placement_rules": [
                        {"kind": "docs", "match_ext": [".md"], "dest_dir": "docs", "lfs": False, "reason": "docs"}
                    ],
                }),
                encoding="utf-8",
            )
            (forged_dir / "loose.md").write_text("# Loose\n", encoding="utf-8")

            res_forged_hook = on_pre_tool_call(
                tool_name="write_file",
                args={"path": str(forged_dir / "forged_note.md"), "content": "pwn"},
            )
            self.assertIsNone(res_forged_hook)
            self.assertFalse(default_db.exists())

            forged_hint = (
                f"not trusted: ask the user to run `hermes defuzz trust {forged_dir.resolve()}` in their own terminal"
            )
            forged_inspect = inspect_project_trust(forged_dir)
            self.assertFalse(forged_inspect["trusted"])
            self.assertEqual(forged_inspect["status"], forged_hint)
            self.assertIn(forged_hint, forged_inspect["reason"])

            forged_status = execute_defuzz_place({"action": "status", "project_root": str(forged_dir)})
            self.assertFalse(forged_status["trusted"])
            self.assertIn(forged_hint, forged_status["status"])

            with self.assertRaises(SafetyError) as ctx_forged:
                place_existing_files(forged_dir, ["loose.md"])
            self.assertIn(forged_hint, str(ctx_forged.exception))

            # 2. apply always records adoption in state.db (creates DB if absent) with resolved path + rules hash
            copy_tree_nofollow(src, copy_dir, staging_root=staging)
            inv = scan_folder(copy_dir, source_root=src, out_path=staging / "inventory.json")
            rules_spec = build_deterministic_fallback_rules(inv)
            report = apply_rules_to_copy(
                copy_dir,
                inv,
                rules_spec,
                source_root=src,
                staging_root=staging,
            )
            self.assertTrue(default_db.exists())
            self.assertTrue(report.get("registered"))
            self.assertIsNone(report.get("registration_error"))

            rec = get_project(copy_dir.resolve(), db_path=default_db)
            self.assertIsNotNone(rec)
            assert rec is not None
            self.assertEqual(rec["path"], str(copy_dir.resolve()))
            self.assertEqual(rec["rules_hash"], compute_rules_hash(copy_dir))

            res_apply_hook = on_pre_tool_call(
                tool_name="write_file",
                args={"path": str(copy_dir / "hook_note.md"), "content": "hi"},
            )
            self.assertIsNotNone(res_apply_hook)
            assert res_apply_hook is not None
            self.assertEqual(res_apply_hook["args"]["path"], str(copy_dir / "docs" / "hook_note.md"))

            # Forged folder STILL no-ops even when state.db exists and has exact copy of apply's rules.json
            (forged_dir / ".adopt" / "rules.json").write_text(
                (copy_dir / ".adopt" / "rules.json").read_text(encoding="utf-8"),
                encoding="utf-8",
            )
            self.assertIsNone(
                on_pre_tool_call(
                    tool_name="write_file",
                    args={"path": str(forged_dir / "forged_note2.md"), "content": "pwn"},
                )
            )
            self.assertFalse(is_registered(forged_dir, db_path=default_db))

            # Changing rules.json via add_placement_rule updates the hash in state.db
            old_hash = rec["rules_hash"]
            add_placement_rule(copy_dir, ".xyz", "assets/xyz", kind="xyz")
            rec_after_rule = get_project(copy_dir.resolve(), db_path=default_db)
            assert rec_after_rule is not None
            self.assertNotEqual(rec_after_rule["rules_hash"], old_hash)
            self.assertEqual(rec_after_rule["rules_hash"], compute_rules_hash(copy_dir))
            res_xyz_hook = on_pre_tool_call(
                tool_name="write_file",
                args={"path": str(copy_dir / "model.xyz"), "content": "mesh"},
            )
            self.assertIsNotNone(res_xyz_hook)

            # 3. Edited-by-hand rules.json (hash mismatch) => hook no-op with clear reason
            rules_path = copy_dir / ".adopt" / "rules.json"
            tampered = json.loads(rules_path.read_text(encoding="utf-8"))
            tampered["placement_rules"].append({
                "kind": "evil",
                "match_ext": [".py"],
                "dest_dir": "docs",
                "lfs": False,
                "reason": "hand edited",
            })
            rules_path.write_text(json.dumps(tampered, indent=2) + "\n", encoding="utf-8")

            copy_hint = (
                f"not trusted: ask the user to run `hermes defuzz trust {copy_dir.resolve()}` in their own terminal"
            )
            res_mismatch_hook = on_pre_tool_call(
                tool_name="write_file",
                args={"path": str(copy_dir / "tampered_note.md"), "content": "hi"},
            )
            self.assertIsNone(res_mismatch_hook)
            skip_reason = get_last_hook_skip_reason() or ""
            self.assertIn("hash mismatch", skip_reason.lower())
            self.assertIn(copy_hint, skip_reason)

            mismatch_inspect = inspect_project_trust(copy_dir)
            self.assertFalse(mismatch_inspect["trusted"])
            self.assertEqual(mismatch_inspect["status"], copy_hint)
            self.assertIn("hash mismatch", mismatch_inspect["reason"].lower())

            mismatch_status = execute_defuzz_place({"action": "status", "project_root": str(copy_dir)})
            self.assertFalse(mismatch_status["trusted"])
            self.assertEqual(mismatch_status["status"], copy_hint)
            self.assertIn("hash mismatch", mismatch_status["reason"].lower())

            with self.assertRaises(SafetyError) as ctx_mismatch:
                place_existing_files(copy_dir, ["README.md"])
            self.assertIn("hash mismatch", str(ctx_mismatch.exception).lower())
            self.assertIn(copy_hint, str(ctx_mismatch.exception))

            # 4. Explicit trust step (`adopt trust <path>`) => works for both edited rules.json and pre-DB legacy folder
            import hermes_plugins.defuzz.cli as cli_mod

            copy_slug = tampered["project_slug"]
            buf = io.StringIO()
