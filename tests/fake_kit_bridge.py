"""Shared fake componentize_bridge helper for kit flow, CLI, and route tests."""

from __future__ import annotations

import copy
import json
import re
from pathlib import Path
from typing import Any, Dict, List, Optional

FIXTURES_DIR = Path(__file__).resolve().parent / "fixtures" / "kit_contract"
_KIT_ID_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")

def load_list_fixture() -> Dict[str, Any]:
    return json.loads((FIXTURES_DIR / "list.json").read_text(encoding="utf-8"))


def load_show_fixture(kit_id: Optional[str] = None) -> Dict[str, Any]:
    """Recorded `kit show --json`: the contract sample (video-production) or any kit by id."""
    if kit_id is None:
        return json.loads((FIXTURES_DIR / "show.json").read_text(encoding="utf-8"))
    return json.loads((FIXTURES_DIR / "shows" / f"{kit_id}.json").read_text(encoding="utf-8"))


# Generated by scripts/gen_kit_fixture.py from the companion plugin; nothing typed by hand.
VIDEO_DECLARED_DIRS: List[Dict[str, str]] = load_show_fixture("video-production")["declared_dirs"]
VIDEO_PLACEMENT_RULES: List[Dict[str, Any]] = load_show_fixture("video-production")["placement_rules"]
VIDEO_KIT_BLOCK: str = load_show_fixture("video-production")["agents_block"].rstrip("\n")


class FakeKitBridge:
    """Fake componentize_bridge serving real contract fixtures for list/show and writing a kit tree on apply."""

    def __init__(
        self,
        *,
        status: str = "ok",
        notice: str = "componentize CLI is unavailable.",
        list_status: Optional[str] = None,
        list_notice: Optional[str] = None,
        show_status: Optional[str] = None,
        show_notice: Optional[str] = None,
        apply_status: Optional[str] = None,
        apply_ok: bool = True,
        apply_env_status: str = "pass",
        apply_notice: Optional[str] = None,
        apply_findings: Optional[List[Dict[str, Any]]] = None,
        check_status: Optional[str] = None,
        check_ok: bool = True,
        check_env_status: str = "pass",
        check_notice: Optional[str] = None,
        check_findings: Optional[List[Dict[str, Any]]] = None,
        declared_dirs: Optional[List[Dict[str, str]]] = None,
        placement_rules: Optional[List[Dict[str, Any]]] = None,
    ) -> None:
        self.list_status = list_status if list_status is not None else status
        self.list_notice = list_notice if list_notice is not None else (
            "componentize kit list pass." if self.list_status == "ok" else notice
        )
        self.show_status = show_status if show_status is not None else status
        self.show_notice = show_notice if show_notice is not None else (
            "componentize kit show pass." if self.show_status == "ok" else notice
        )
        self.apply_status = apply_status if apply_status is not None else status
        self.apply_ok = apply_ok
        self.apply_env_status = apply_env_status
        self.apply_notice = apply_notice if apply_notice is not None else (
            "componentize kit apply pass." if self.apply_status == "ok" else notice
        )
        self.apply_findings = list(apply_findings) if apply_findings is not None else []
        self.check_status = check_status if check_status is not None else status
        self.check_ok = check_ok
        self.check_env_status = check_env_status
        self.check_notice = check_notice if check_notice is not None else (
            "componentize kit check pass." if self.check_status == "ok" else notice
        )
        self.check_findings = list(check_findings) if check_findings is not None else []
        # None means "what the recorded kit declares" (per kit id, from the generated fixture).
        self._declared_override = [dict(d) for d in declared_dirs] if declared_dirs is not None else None
        self._placement_override = [dict(r) for r in placement_rules] if placement_rules is not None else None
        self._list_data = load_list_fixture()
        self._known_ids = {k["id"] for k in self._list_data["kits"]}
        self._show_data = {kid: load_show_fixture(kid) for kid in sorted(self._known_ids)}

        self.list_calls: List[Dict[str, Any]] = []
        self.show_calls: List[Dict[str, Any]] = []
        self.apply_calls: List[Dict[str, Any]] = []
        self.check_calls: List[Dict[str, Any]] = []

    @property
    def declared_dirs(self) -> List[Dict[str, str]]:
        """Folders of the last applied/checked kit (video-production before any call)."""
        return self._dirs_for(self._current_kit)

    @property
    def placement_rules(self) -> List[Dict[str, Any]]:
        return self._rules_for(self._current_kit)

    _current_kit = "video-production"

    def _dirs_for(self, kit_id: str) -> List[Dict[str, str]]:
        if self._declared_override is not None:
            return [dict(d) for d in self._declared_override]
        return copy.deepcopy(self._show_data.get(kit_id, {}).get("declared_dirs", []))

    def _rules_for(self, kit_id: str) -> List[Dict[str, Any]]:
        if self._placement_override is not None:
            return [dict(r) for r in self._placement_override]
        return copy.deepcopy(self._show_data.get(kit_id, {}).get("placement_rules", []))

    def kit_list(self, *, timeout: Optional[float] = None) -> Dict[str, Any]:
        self.list_calls.append({"timeout": timeout})
        if self.list_status != "ok":
            return {
                "status": self.list_status,
                "data": None,
                "notice": self.list_notice,
                "exit": None if self.list_status == "unavailable" else 2,
            }
        return {
            "status": "ok",
            "data": copy.deepcopy(self._list_data),
            "notice": self.list_notice,
            "exit": 0,
        }

    def kit_show(self, kit_id: str, *, timeout: Optional[float] = None) -> Dict[str, Any]:
        self.show_calls.append({"kit_id": kit_id, "timeout": timeout})
        if not isinstance(kit_id, str) or not _KIT_ID_RE.match(kit_id):
            return {
                "status": "error",
                "data": None,
                "notice": "invalid kit_id: must match ^[a-z0-9]+(-[a-z0-9]+)*$",
                "exit": None,
            }
        if self.show_status != "ok":
            return {
                "status": self.show_status,
                "data": None,
                "notice": self.show_notice,
                "exit": None if self.show_status == "unavailable" else 2,
            }
        if kit_id not in self._known_ids:
            return {
                "status": "error",
                "data": None,
                "notice": f"componentize kit show error (exit 2): unknown kit {kit_id!r}",
                "exit": 2,
            }
        data = copy.deepcopy(self._show_data[kit_id])
        return {
            "status": "ok",
            "data": data,
            "notice": self.show_notice,
            "exit": 0,
        }

    def kit_apply(
        self,
        kit_id: str,
        dest: Path | str,
        variables: Optional[Dict[str, str]] = None,
        *,
        timeout: Optional[float] = None,
    ) -> Dict[str, Any]:
        dest_path = Path(dest)
        self.apply_calls.append(
            {"kit_id": kit_id, "dest": dest_path, "variables": variables, "timeout": timeout}
        )
        if not isinstance(kit_id, str) or not _KIT_ID_RE.match(kit_id):
            return {
                "status": "error",
                "data": None,
                "notice": "invalid kit_id: must match ^[a-z0-9]+(-[a-z0-9]+)*$",
                "exit": None,
            }
        if self.apply_status != "ok":
            return {
                "status": self.apply_status,
                "data": None,
                "notice": self.apply_notice,
                "exit": None if self.apply_status == "unavailable" else 2,
            }
        if kit_id not in self._known_ids:
            return {
                "status": "error",
                "data": None,
                "notice": f"componentize kit apply error (exit 2): unknown kit {kit_id!r}",
                "exit": 2,
            }
        self._current_kit = kit_id
        if not self.apply_ok or self.apply_env_status != "pass":
            return {
                "status": "ok",
                "data": {
                    "schema": "componentize.kit/1",
                    "ok": self.apply_ok,
                    "status": self.apply_env_status,
                    "error": None,
                    "findings": list(self.apply_findings),
                    "root": str(dest_path),
                    "kit": kit_id,
                    "items": [],
                    "declared_dirs": [dict(d) for d in self.declared_dirs],
                    "placement_rules": [dict(r) for r in self.placement_rules],
                },
                "notice": self.apply_notice,
                "exit": 1,
            }

        dest_path.mkdir(parents=True, exist_ok=True)
        items: List[Dict[str, str]] = []
        for entry in self.declared_dirs:
            rel_dir = entry["dir"]
            folder = dest_path / rel_dir
            folder.mkdir(parents=True, exist_ok=True)
            (folder / ".gitkeep").write_text("", encoding="utf-8")
            items.append({"path": rel_dir, "state": "created"})

        # Lay out the rest of the recorded tree (placeholder file bodies; AGENTS.md below).
        show = self._show_data[kit_id]
        for rel in show.get("tree", []):
            target = dest_path / rel
            if rel.endswith("/"):
                target.mkdir(parents=True, exist_ok=True)
            elif rel != "AGENTS.md" and not target.exists():
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text("", encoding="utf-8")
        # The real CLI writes the applied kit's managed block; accept_kit checks for it.
        block = show["agents_block"].rstrip("\n")
        agents_text = f"# {dest_path.name}\n\n{block}\n"
        (dest_path / "AGENTS.md").write_text(agents_text, encoding="utf-8")

        return {
            "status": "ok",
            "data": {
                "schema": "componentize.kit/1",
                "ok": True,
                "status": "pass",
                "error": None,
                "findings": [],
                "root": str(dest_path),
                "kit": kit_id,
                "items": items,
                "declared_dirs": [dict(d) for d in self.declared_dirs],
                "placement_rules": [dict(r) for r in self.placement_rules],
            },
            "notice": self.apply_notice,
            "exit": 0,
        }

    def kit_check(self, kit_id: str, dest: Path | str, *, timeout: Optional[float] = None) -> Dict[str, Any]:
        dest_path = Path(dest)
        self.check_calls.append({"kit_id": kit_id, "dest": dest_path, "timeout": timeout})
        if kit_id in self._known_ids:
            self._current_kit = kit_id
        if self.check_status != "ok":
            return {
                "status": self.check_status,
                "data": None,
                "notice": self.check_notice,
                "exit": None if self.check_status == "unavailable" else 2,
            }
        return {
            "status": "ok",
            "data": {
                "schema": "componentize.kit/1",
                "ok": self.check_ok,
                "status": self.check_env_status,
                "error": None,
                "findings": list(self.check_findings),
                "root": str(dest_path),
                "kit": kit_id,
                "items": [
                    {"path": d["dir"], "state": "present"} for d in self.declared_dirs
                ],
                "declared_dirs": [dict(d) for d in self.declared_dirs],
                "placement_rules": [dict(r) for r in self.placement_rules],
            },
            "notice": self.check_notice,
            "exit": 0 if (self.check_ok and self.check_env_status == "pass") else 1,
        }

    def install(self, monkeypatch: Any, bridge_module: Any) -> "FakeKitBridge":
        """Monkeypatch kit_list, kit_show, kit_apply, and kit_check onto bridge_module."""
        monkeypatch.setattr(bridge_module, "kit_list", self.kit_list)
        monkeypatch.setattr(bridge_module, "kit_show", self.kit_show)
        monkeypatch.setattr(bridge_module, "kit_apply", self.kit_apply)
        monkeypatch.setattr(bridge_module, "kit_check", self.kit_check)
        return self
